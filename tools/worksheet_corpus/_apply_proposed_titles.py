def apply_all():
    rows = []
    for draft_id, title in PROPOSED.items():
        draft = load_draft(draft_id)
        if not draft or draft.get('status') in ('skipped', 'imported'):
            continue
        if draft.get('title_origin') in ('proposed', 'manual'):
            continue
        old = draft.get('title') or ''
        if not title_looks_from_filename(old, draft.get('rel_path') or ''):
            continue
        apply_proposed_title(draft, title)
        save_draft(draft)
        rows.append((draft_id, old, title))
    return rows


if __name__ == '__main__':
    for key, old, new in apply_all():
        print(f'{key}: {old} → {new}')
