I = []


def add(did, i, pairs, warning=''):
    answers = [a for a, _s in pairs]
    solutions = [_s for _a, _s in pairs]
    I.append({
        'id': did,
        'i': i,
        'answer': '',
        'solution': '',
        'subitem_answers': answers,
        'subitem_solutions': solutions,
        'warning': warning,
    })


def flush(did):
    rows = [x for x in I if x['id'] == did]
    if rows:
        apply_solutions(rows)


def A(ans, body):
    return (ans, body.rstrip() + f'\nОтвет: {ans}.')


