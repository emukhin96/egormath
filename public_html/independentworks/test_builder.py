    def test_create_directly_from_current_worksheet(self):
        from django.utils import timezone
        from accounts.models import Profile
        from worksheets.models import Worksheet, WorksheetItem
        teacher = get_user_model().objects.create_user('sheet_to_work')
        Profile.objects.update_or_create(user=teacher, defaults={'role': Profile.ROLE_TEACHER})
        self.client.force_login(teacher)
        sheet = Worksheet.objects.create(owner=teacher, title='Текущий листок')
        task = Task.objects.create(text_latex='Задача с подпунктами')
        a = TaskSubitem.objects.create(task=task, order=1, text_latex='Первый')
        b = TaskSubitem.objects.create(task=task, order=2, text_latex='Второй')
        WorksheetItem.objects.create(worksheet=sheet, order=1, rubric='Заголовок', text_latex='Пояснение')
        item = WorksheetItem.objects.create(worksheet=sheet, order=2, task=task, all_subitems=False)
        item.subitems.set([b])
        WorksheetItem.objects.create(worksheet=sheet, order=3, task=task, deleted_at=timezone.now())
        url = reverse('independentworks:create_from_worksheet', args=[sheet.pk])
        page = self.client.get(reverse('worksheet_detail', args=[sheet.pk]))
        self.assertContains(page, 'method="post" action="' + url + '"')
        self.assertEqual(self.client.get(url).status_code, 405)
        self.assertFalse(Work.objects.exists())
        response = self.client.post(url)
        work = Work.objects.get()
        self.assertRedirects(response, reverse('independentworks:edit', args=[work.pk]))
        self.assertEqual((work.title, work.owner, work.source_worksheet), (sheet.title, teacher, sheet))
        worksheet_catalog = self.client.get(reverse('worksheet_list'))
        self.assertContains(
            worksheet_catalog, reverse('worksheet_detail', args=[sheet.pk]))
        self.assertNotContains(
            worksheet_catalog, reverse('independentworks:edit', args=[work.pk]))
        self.assertTrue(Worksheet.objects.filter(pk=sheet.pk).exists())
        positions = list(work.positions.all())
        self.assertEqual(len(positions), 2)
        self.assertEqual(positions[0].text, 'Заголовок\nПояснение')
        candidate = positions[1].candidates.get()
        self.assertEqual((candidate.task, candidate.subitem_ids), (task, [b.pk]))
        item.subitems.set([a])
        candidate.refresh_from_db()
        self.assertEqual(candidate.subitem_ids, [b.pk])
        other = get_user_model().objects.create_user('other_sheet_owner')
        foreign = Worksheet.objects.create(owner=other, title='Чужой листок')
        self.assertEqual(self.client.post(reverse('independentworks:create_from_worksheet', args=[foreign.pk])).status_code, 404)
        with override_settings(INDEPENDENT_WORKS_ENABLED=False):
            self.assertEqual(self.client.post(url).status_code, 404)
        student = get_user_model().objects.create_user('sheet_student')
        self.client.force_login(student)
        self.assertEqual(self.client.post(url).status_code, 403)
        self.assertEqual(Work.objects.count(), 1)
